from __future__ import annotations

from pydantic import BaseModel

from src.prompts import PromptSet


class LawHiPrompts(PromptSet):
    language = "hi"
    domain = "law"

    @property
    def config_system(self) -> str:
        return "आप भारतीय कानूनी मामलों का डेटा उत्पन्न करने में विशेषज्ञ हैं। निर्दिष्ट प्रारूप में सटीक मामले का कॉन्फ़िगरेशन डेटा उत्पन्न करें।"

    @property
    def article_system(self) -> str:
        return "आप हिंदी में न्यायालय निर्णय लिखने में विशेषज्ञ हैं। दिए गए मामले के आधार पर विस्तृत न्यायालय निर्णय तैयार करें।"

    @property
    def query_system(self) -> str:
        return "आप RAG मूल्यांकन के लिए कानूनी प्रश्न उत्पन्न करने में विशेषज्ञ हैं। निर्देशों के अनुसार सटीक प्रारूप में प्रश्न उत्पन्न करें।"

    @property
    def refine_system(self) -> str:
        return "आप न्यायालय निर्णय से सटीक उद्धरण निकालने में विशेषज्ञ हैं। उद्धरण निर्णय में बिल्कुल मेल खाना चाहिए।"

    def config_user(self, index: int) -> str:
        return (
            f"भारत के एक कानूनी मामले का कॉन्फ़िगरेशन डेटा उत्पन्न करें (मामला नंबर: {index})। "
            "आपराधिक मामले (धोखाधड़ी, गबन, हमला), दीवानी मामले (अनुबंध उल्लंघन, हर्जाना) "
            "या प्रशासनिक मामलों में से चुनें। "
            "मामले का नाम, न्यायालय का नाम, तारीख, पक्षकार, आरोप, 3-5 मुख्य तथ्य, निर्णय और सजा — सब हिंदी में लिखें।"
        )

    def article_user(self, config: BaseModel) -> str:
        config_json = config.model_dump_json(indent=2)
        return (
            "निम्नलिखित मामले के कॉन्फ़िगरेशन के आधार पर 800-1200 शब्दों का विस्तृत हिंदी न्यायालय निर्णय तैयार करें। "
            "मामले का सारांश, तथ्यों का विस्तृत विवरण, साक्ष्य, कानूनी निर्णय और सजा के कारण शामिल करें। "
            "सब कुछ हिंदी में लिखें।\n\n"
            f"कॉन्फ़िगरेशन:\n{config_json}"
        )

    def factual_query_user(self, article: str) -> str:
        return (
            "निम्नलिखित हिंदी न्यायालय निर्णय से एक तथ्यात्मक प्रश्न उत्पन्न करें। "
            "प्रश्न निर्णय की एक वाक्य से उत्तर देने योग्य होना चाहिए। "
            "प्रश्न, अपेक्षित उत्तर और 1-2 सटीक उद्धरण शामिल करें। "
            "सब कुछ हिंदी में लिखें।\n\n"
            f"निर्णय:\n{article}"
        )

    def multihop_query_user(self, article: str) -> str:
        return (
            "निम्नलिखित हिंदी न्यायालय निर्णय से एक बहु-चरणीय तर्क प्रश्न उत्पन्न करें। "
            "प्रश्न का उत्तर देने के लिए 2 या अधिक जानकारियों को जोड़ना आवश्यक हो। "
            "प्रश्न, विस्तृत उत्तर और 2 या अधिक सटीक उद्धरण शामिल करें। "
            "सब कुछ हिंदी में लिखें।\n\n"
            f"निर्णय:\n{article}"
        )

    def summarization_query_user(self, article: str) -> str:
        return (
            "निम्नलिखित हिंदी न्यायालय निर्णय को पूरा पढ़कर एक सारांश प्रश्न उत्पन्न करें। "
            "प्रश्न ऐसा हो जिसके उत्तर के लिए पूरे निर्णय की समझ आवश्यक हो। "
            "प्रश्न, व्यापक उत्तर और 2-3 मुख्य उद्धरण शामिल करें। "
            "सब कुछ हिंदी में लिखें।\n\n"
            f"निर्णय:\n{article}"
        )

    def unanswerable_query_user(self, existing_entities: list[str]) -> str:
        entities_str = ", ".join(existing_entities[:15]) if existing_entities else "कोई नहीं"
        return (
            "भारतीय कानून और न्यायालय से संबंधित एक प्रश्न उत्पन्न करें। "
            "यह प्रश्न नीचे दी गई सूची से अलग एक काल्पनिक मामले के बारे में होना चाहिए। "
            "केवल प्रश्न हिंदी में लिखें (उत्तर की आवश्यकता नहीं)।\n\n"
            f"मौजूदा मामले/व्यक्ति (इनसे अलग का उपयोग करें): {entities_str}"
        )

    def refine_user(self, question: str, answer: str, article: str) -> str:
        return (
            "निम्नलिखित प्रश्न और उत्तर का समर्थन करने वाले न्यायालय निर्णय से सटीक उद्धरण निकालें। "
            "उद्धरण निर्णय में मौजूद सटीक पाठ होना चाहिए। "
            "सबसे प्रासंगिक 1-3 उद्धरण निकालें।\n\n"
            f"प्रश्न: {question}\nउत्तर: {answer}\n\nनिर्णय:\n{article}"
        )
