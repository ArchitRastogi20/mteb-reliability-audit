from __future__ import annotations

from pydantic import BaseModel

from src.prompts import PromptSet


class FinanceHiPrompts(PromptSet):
    language = "hi"
    domain = "finance"

    @property
    def config_system(self) -> str:
        return "आप भारतीय वित्तीय कंपनियों का डेटा उत्पन्न करने में विशेषज्ञ हैं। निर्दिष्ट प्रारूप में सटीक कंपनी कॉन्फ़िगरेशन डेटा उत्पन्न करें।"

    @property
    def article_system(self) -> str:
        return "आप हिंदी में वित्तीय रिपोर्ट लिखने में विशेषज्ञ हैं। दी गई कंपनी कॉन्फ़िगरेशन के आधार पर विस्तृत वार्षिक रिपोर्ट तैयार करें।"

    @property
    def query_system(self) -> str:
        return "आप RAG मूल्यांकन के लिए प्रश्न उत्पन्न करने में विशेषज्ञ हैं। निर्देशों के अनुसार सटीक प्रारूप में प्रश्न उत्पन्न करें।"

    @property
    def refine_system(self) -> str:
        return "आप दस्तावेज़ से सटीक उद्धरण निकालने में विशेषज्ञ हैं। उद्धरण दस्तावेज़ में बिल्कुल मेल खाना चाहिए।"

    def config_user(self, index: int) -> str:
        return (
            f"भारत की एक वित्तीय कंपनी का कॉन्फ़िगरेशन डेटा उत्पन्न करें (कंपनी नंबर: {index})। "
            "बैंकिंग, बीमा, एनबीएफसी, शेयर बाजार, रियल एस्टेट जैसे क्षेत्रों में से चुनें। "
            "कंपनी का नाम, उद्योग, स्थापना वर्ष, मुख्यालय, 2-3 महत्वपूर्ण घटनाएं (तारीख, विवरण, वित्तीय प्रभाव), "
            "राजस्व और लाभ मार्जिन — सब हिंदी में लिखें।"
        )

    def article_user(self, config: BaseModel) -> str:
        config_json = config.model_dump_json(indent=2)
        return (
            "निम्नलिखित कंपनी कॉन्फ़िगरेशन के आधार पर 800-1200 शब्दों की विस्तृत हिंदी वार्षिक रिपोर्ट तैयार करें। "
            "कंपनी का परिचय, वित्तीय प्रदर्शन, महत्वपूर्ण घटनाओं का विस्तृत विवरण, बाजार विश्लेषण शामिल करें। "
            "सब कुछ हिंदी में लिखें, अंग्रेजी का उपयोग न करें।\n\n"
            f"कॉन्फ़िगरेशन:\n{config_json}"
        )

    def factual_query_user(self, article: str) -> str:
        return (
            "निम्नलिखित हिंदी लेख से एक तथ्यात्मक प्रश्न उत्पन्न करें। "
            "प्रश्न लेख की एक वाक्य से उत्तर देने योग्य होना चाहिए। "
            "प्रश्न, अपेक्षित उत्तर और 1-2 सटीक उद्धरण शामिल करें। "
            "सब कुछ हिंदी में लिखें।\n\n"
            f"लेख:\n{article}"
        )

    def multihop_query_user(self, article: str) -> str:
        return (
            "निम्नलिखित हिंदी लेख से एक बहु-चरणीय तर्क प्रश्न उत्पन्न करें। "
            "प्रश्न का उत्तर देने के लिए 2 या अधिक जानकारियों को जोड़ना आवश्यक हो। "
            "प्रश्न, विस्तृत उत्तर और 2 या अधिक सटीक उद्धरण शामिल करें। "
            "सब कुछ हिंदी में लिखें।\n\n"
            f"लेख:\n{article}"
        )

    def summarization_query_user(self, article: str) -> str:
        return (
            "निम्नलिखित हिंदी लेख को पूरा पढ़कर एक सारांश प्रश्न उत्पन्न करें। "
            "प्रश्न ऐसा हो जिसके उत्तर के लिए पूरे लेख की समझ आवश्यक हो। "
            "प्रश्न, व्यापक उत्तर और 2-3 मुख्य उद्धरण शामिल करें। "
            "सब कुछ हिंदी में लिखें।\n\n"
            f"लेख:\n{article}"
        )

    def unanswerable_query_user(self, existing_entities: list[str]) -> str:
        entities_str = ", ".join(existing_entities[:15]) if existing_entities else "कोई नहीं"
        return (
            "भारत के वित्तीय क्षेत्र से संबंधित एक प्रश्न उत्पन्न करें। "
            "यह प्रश्न नीचे दी गई सूची से अलग एक काल्पनिक कंपनी के बारे में होना चाहिए। "
            "केवल प्रश्न हिंदी में लिखें (उत्तर की आवश्यकता नहीं)।\n\n"
            f"मौजूदा कंपनियां (इनसे अलग कंपनी का उपयोग करें): {entities_str}"
        )

    def refine_user(self, question: str, answer: str, article: str) -> str:
        return (
            "निम्नलिखित प्रश्न और उत्तर का समर्थन करने वाले लेख से सटीक उद्धरण निकालें। "
            "उद्धरण लेख में मौजूद सटीक पाठ होना चाहिए। "
            "सबसे प्रासंगिक 1-3 उद्धरण निकालें।\n\n"
            f"प्रश्न: {question}\nउत्तर: {answer}\n\nलेख:\n{article}"
        )
